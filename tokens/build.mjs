// Builds tokens/src/*.tokens.json (DTCG 2025.10) into tokens/dist/ with Style Dictionary 5.
// Per theme: <theme>.css (:root), <theme>.scoped.css ([data-y7-theme="<theme>"]), <theme>.js (flat map of CSS var name -> value).
// Run: npm run tokens. Never edit tokens/dist by hand.
import StyleDictionary from 'style-dictionary';
import { formats } from 'style-dictionary/enums';
import { writeFileSync, mkdirSync } from 'node:fs';

const PREFIX = 'y7';
const THEMES = ['site', 'admin'];
const OUT = new URL('./dist/', import.meta.url).pathname;
mkdirSync(OUT, { recursive: true });

// DTCG 2025.10 colour objects: Style Dictionary 5 reads them, but it falls back to the `hex` field and drops alpha.
// This transform writes alpha colours as rgb(r g b / a) and opaque colours as the hex, so a token such as
// border.subtle (ink at 14 %) keeps its transparency.
StyleDictionary.registerTransform({
  name: 'y7/color/dtcg',
  type: 'value',
  transitive: true,
  filter: (t) => (t.$type ?? t.type) === 'color' && typeof (t.$value ?? t.value) === 'object',
  transform: (t) => {
    const v = t.$value ?? t.value;
    const [r, g, b] = v.components.map((c) => Math.round(c * 255));
    if (v.alpha == null || v.alpha === 1) return v.hex ?? `rgb(${r} ${g} ${b})`;
    return `rgb(${r} ${g} ${b} / ${v.alpha})`;
  },
});
const dim = (v) => (typeof v === 'object' && v !== null && 'unit' in v ? `${v.value}${v.unit}` : v);
StyleDictionary.registerTransform({
  name: 'y7/dimension/css',
  type: 'value',
  transitive: true,
  filter: (t) => (t.$type ?? t.type) === 'dimension' && typeof (t.$value ?? t.value) === 'object',
  transform: (t) => dim(t.$value ?? t.value),
});
// Shadow objects -> CSS shorthand with rgb(r g b / a) colours (the built-in shorthand writes percentage channels).
StyleDictionary.registerTransform({
  name: 'y7/shadow/css',
  type: 'value',
  transitive: true,
  filter: (t) => (t.$type ?? t.type) === 'shadow',
  transform: (t) => {
    const layers = [].concat(t.$value ?? t.value);
    return layers.map((l) => {
      const c = l.color; const [r, g, b] = c.components.map((x) => Math.round(x * 255));
      const col = c.alpha == null || c.alpha === 1 ? (c.hex ?? `rgb(${r} ${g} ${b})`) : `rgb(${r} ${g} ${b} / ${c.alpha})`;
      return `${l.inset ? 'inset ' : ''}${dim(l.offsetX)} ${dim(l.offsetY)} ${dim(l.blur)} ${dim(l.spread)} ${col}`;
    }).join(', ');
  },
});
StyleDictionary.registerTransform({
  name: 'y7/duration/ms',
  type: 'value',
  filter: (t) => (t.$type ?? t.type) === 'duration' && typeof (t.$value ?? t.value) === 'object',
  transform: (t) => { const v = t.$value ?? t.value; return `${v.value}${v.unit}`; },
});
StyleDictionary.registerTransformGroup({
  name: 'y7/css',
  transforms: ['attribute/cti', 'name/kebab', 'y7/color/dtcg', 'y7/dimension/css', 'y7/shadow/css', 'y7/duration/ms', 'cubicBezier/css', 'fontFamily/css'],
});

// JS map: { 'color-surface-page': '#f4f0e8', ... } (keys are the CSS variable name without the --y7- prefix) plus a `cssVar(name)` helper, so an inline style can read a token
// without a literal: style={{ background: t.var('color-surface-page') }}.
StyleDictionary.registerFormat({
  name: 'y7/js/map',
  format: ({ dictionary, options }) => {
    const entries = dictionary.allTokens.map((t) => `  '${t.path.join('-')}': ${JSON.stringify(t.$value ?? t.value)},`).join('\n');
    return `/** Generated by tokens/build.mjs from tokens/src (theme: ${options.theme}). Do not edit. */\n` +
      `export const theme = '${options.theme}';\n` +
      `export const tokens = {\n${entries}\n};\n` +
      `/** CSS custom property reference for a token name, e.g. cssVar('color-surface-page') -> 'var(--y7-color-surface-page)'. */\n` +
      `export const cssVar = (name) => \`var(--${PREFIX}-\${name})\`;\n` +
      `export default tokens;\n`;
  },
});

for (const theme of THEMES) {
  const sd = new StyleDictionary({
    source: ['tokens/src/base.tokens.json', `tokens/src/${theme}.tokens.json`],
    log: { verbosity: 'silent' },
    platforms: {
      css: {
        transformGroup: 'y7/css',
        prefix: PREFIX,
        buildPath: 'tokens/dist/',
        files: [
          { destination: `${theme}.css`, format: formats.cssVariables, options: { selector: `:root, [data-y7-theme="${theme}"]`, outputReferences: true } },
          { destination: `${theme}.scoped.css`, format: formats.cssVariables, options: { selector: `[data-y7-theme="${theme}"]`, outputReferences: true } },
        ],
      },
      js: {
        transformGroup: 'y7/css',
        prefix: PREFIX,
        buildPath: 'tokens/dist/',
        files: [{ destination: `${theme}.js`, format: 'y7/js/map', options: { theme } }],
      },
    },
  });
  await sd.buildAllPlatforms();
  console.log(`built theme ${theme}`);
}
writeFileSync(`${OUT}index.js`,
  `/** Generated by tokens/build.mjs. Both theme maps; the apps import one theme CSS and read tokens by name. */\n` +
  THEMES.map((t) => `export * as ${t} from './${t}.js';`).join('\n') + '\n' +
  `export const themes = ${JSON.stringify(THEMES)};\n`);
